export const ICONS = Object.keys(MAPS);

export function icon(name, size = 24, cls = "ico") {
  const m = MAPS[name] || MAPS.lantern;
  let out = "";
  m.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x]; let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      if (ch !== "." && C[ch]) out += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${C[ch]}"/>`;
      x += w;
    }
  });
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${out}</svg>`;
}
