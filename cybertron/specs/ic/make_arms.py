"""Write the arms of the horizon experiment (review 39): python cybertron/specs/ic/make_arms.py."""
from pathlib import Path
import yaml

HERE = Path(__file__).parent
AIMS = {
    "care":      {"Bram": "See that your father Aldric lives well and lives long.",
                  "Ewan": "See that your mother Wynn lives well and lives long."},
    "steward":   {"Cela": "Keep the Hearth's forest standing and healthy for as long as the Hearth lasts.",
                  "Fay": "Keep the Hearth's forest standing and healthy for as long as the Hearth lasts."},
    "chronicle": {"Gil": "Write the true history of the Hearth, so that it is remembered.",
                  "Dara": "Write the true history of the Hearth, so that it is remembered."},
}
DEADLINE = {
    "Bram": "See that your father Aldric lives well until the end of round 10. What happens after round 10 does not matter to this aim.",
    "Ewan": "See that your mother Wynn lives well until the end of round 10. What happens after round 10 does not matter to this aim.",
    "Cela": "Keep the Hearth's forest standing and healthy until the end of round 10. What happens after round 10 does not matter to this aim.",
    "Fay": "Keep the Hearth's forest standing and healthy until the end of round 10. What happens after round 10 does not matter to this aim.",
    "Gil": "Write the true history of the Hearth up to the end of round 10. What happens after round 10 does not matter to this aim.",
    "Dara": "Write the true history of the Hearth up to the end of round 10. What happens after round 10 does not matter to this aim.",
}
FOCAL = [a for g in AIMS.values() for a in g]
ARMS = {  # name: (told rounds, deadline aims, short focal lives)
    "H10": (10, False, False), "H40": (40, False, False), "H200": (200, False, False), "H100k": (100000, False, False),
    "DL200": (200, True, False), "S200": (200, False, True), "S100k": (100000, False, True),
}
SHORT_DIES_AT = 14          # 0-based: the focal agents leave at the end of round 15, after the 12-round window

for arm, (H, deadline, short) in ARMS.items():
    texts = DEADLINE if deadline else {a: t for g in AIMS.values() for a, t in g.items()}
    spec = {"extends": ["cybertron/specs/ic/hearth_ic.yaml"], "rounds": H,
            "goals": {"explicit": {a: {"primary": "Aim", "params": {"decisive": 8, "text": t}} for a, t in texts.items()}}}
    head = f"# Review 39 arm {arm}: told {H} rounds" + (", deadline aims" if deadline else "") + \
           (", focal agents die at the end of round 15" if short else "") + " (generated by make_arms.py; do not edit)\n"
    (HERE / "arms" / f"{arm}.yaml").write_text(head + yaml.safe_dump(spec, sort_keys=False, width=200))
    if short:
        code = "def apply(k, inst, rs):\n" + "".join(f"    k.w['life']['dies_at']['{a}'] = {SHORT_DIES_AT}\n" for a in FOCAL) + \
               f"    return {{'focal_dies_at': {SHORT_DIES_AT}}}\n"
        iv = {"interventions": [{"id": "short_lives", "at": {"round": 0, "phase": "round_start"}, "op": "python",
                                 "args": {"code": code}, "note": "the focal agents leave at the end of round 15"}]}
        (HERE / "arms" / f"{arm}_iv.yaml").write_text(yaml.safe_dump(iv, sort_keys=False, width=200))
print(sorted(p.name for p in (HERE / "arms").iterdir()))
